// STRIDE must be coprime with AFFIRMATIONS.length so that consecutive days walk the whole
// list before any text repeats. 97 is prime, so it is coprime with any length that is not a multiple of 97.
export const STRIDE = 97;

// Whole days since 1970-01-01 for a local ISO date (YYYY-MM-DD). Pure arithmetic, no timezone.
// Returns NaN for anything malformed or not a real calendar date (e.g. 2026-13-45, 2026-02-31).
export function dayNumber(isoDate) {
  if (typeof isoDate !== "string" || !/^[0-9]{4}-[0-9]{2}-[0-9]{2}$/.test(isoDate)) return NaN;
  const [y, m, d] = isoDate.split("-").map(Number);
  if (m < 1 || m > 12 || d < 1 || d > 31) return NaN;
  const ms = Date.UTC(y, m - 1, d);
  const back = new Date(ms);
  if (back.getUTCMonth() !== m - 1 || back.getUTCDate() !== d) return NaN;
  return Math.round(ms / 86400000);
}

// The affirmation for a local ISO date. Same date -> same text, everywhere.
// A malformed date falls back to AFFIRMATIONS[0]; this never throws and never returns an empty body.
export function affirmationFor(isoDate) {
  const n = AFFIRMATIONS.length;
  const day = dayNumber(isoDate);
  if (Number.isNaN(day)) return AFFIRMATIONS[0];
  const index = (((day % n) * STRIDE) % n + n) % n;
  return AFFIRMATIONS[index];
}
